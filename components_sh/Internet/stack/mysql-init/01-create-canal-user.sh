#!/bin/sh
set -eu

mysql --protocol=socket -uroot -p"${MYSQL_ROOT_PASSWORD}" <<SQL
CREATE DATABASE IF NOT EXISTS demo_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS 'demo_app'@'%' IDENTIFIED BY '${MYSQL_PASSWORD}';
ALTER USER 'demo_app'@'%' IDENTIFIED BY '${MYSQL_PASSWORD}';
GRANT ALL PRIVILEGES ON demo_db.* TO 'demo_app'@'%';
CREATE USER IF NOT EXISTS 'canal'@'%' IDENTIFIED BY '${CANAL_PASSWORD}';
ALTER USER 'canal'@'%' IDENTIFIED BY '${CANAL_PASSWORD}';
GRANT SELECT, REPLICATION SLAVE, REPLICATION CLIENT, SHOW VIEW, RELOAD ON *.* TO 'canal'@'%';
FLUSH PRIVILEGES;
SQL
